import { useEffect } from 'react'

/**
 * What a crawler is told about a page.
 *
 * `app.alkachof.mx` is the canonical host — the address that gets ranked,
 * shared and quoted. `alkachof.mx` redirects onto it and is reserved for a
 * company site later. See `blueprint.SEO.md` §3.
 *
 * Two things write the tags in this file, and they must agree:
 *
 *  - **`scripts/prerender.mjs`**, at build time, into the static HTML. This is
 *    the half that matters for findability: social and AI crawlers never run
 *    JavaScript, so the only metadata they will ever see is the one baked into
 *    the file.
 *  - **`useDocumentMeta`**, at runtime, as the user navigates. A client-side
 *    route change does not re-fetch the document, so without this every route
 *    after the first would keep the previous page's title.
 *
 * Changing a default here therefore means re-running the build, not just a
 * reload.
 */

/** Canonical origin. The fallback is production on purpose — the same reason
 *  `shareUrl.ts` does it: a link minted with an unset env var must still open. */
export const SITE_URL = (
  import.meta.env.VITE_PUBLIC_APP_URL ?? 'https://app.alkachof.mx'
).replace(/\/$/, '')

export const SITE_NAME = 'Alkachof'

/**
 * Never ship the bare brand as a title.
 *
 * `alkachof` is one letter from `alcachofa` — artichoke — and search engines
 * read it as a misspelling, against a deep commercial corpus (Mercado Libre,
 * Amazon, recipes). Pairing the name with the category on every surface is what
 * gives the token a non-vegetable context to attach to. `blueprint.SEO.md` §7.
 */
export const DEFAULT_TITLE = 'Alkachof — catálogo digital gratis para vender por WhatsApp'

/** ~155 characters: longer is truncated in a result with an ellipsis. */
export const DEFAULT_DESCRIPTION =
  'Publica tu catálogo con las fotos de tu celular y compártelo por WhatsApp. ' +
  'Sin comisiones y sin planes: Alkachof es gratis para vendedores pequeños en México.'

/** 1200×630, the size every social crawler crops to. Generated by
 *  `scripts/make-og-image.mjs`; marketing replaces the art, not the size. */
export const DEFAULT_OG_IMAGE = `${SITE_URL}/og.png`

export type DocumentMeta = {
  title?: string
  description?: string
  /** Absolute path, e.g. `/catalog/abc`. Resolved against `SITE_URL`. */
  canonicalPath?: string
  /** Absolute URL. A relative one is invisible to a crawler that cannot resolve it. */
  image?: string
  /** Keeps a page out of the index. For anything behind or about auth. */
  noIndex?: boolean
}

function upsertMeta(selector: string, attr: 'name' | 'property', key: string, content: string) {
  let el = document.head.querySelector<HTMLMetaElement>(selector)
  if (!el) {
    el = document.createElement('meta')
    el.setAttribute(attr, key)
    document.head.appendChild(el)
  }
  el.setAttribute('content', content)
}

/**
 * Applies a route's metadata to the live document, and puts back what was there
 * on the way out.
 *
 * The restore is not housekeeping. Routes that do not call this hook inherit
 * whatever the last one left behind, so a visitor going catalog → login would
 * otherwise sit on a page titled after a shop they are no longer looking at —
 * which is also what would get bookmarked and shared.
 */
export function useDocumentMeta(meta: DocumentMeta): void {
  const { title, description, canonicalPath, image, noIndex } = meta

  useEffect(() => {
    const previousTitle = document.title

    const resolvedTitle = title ?? DEFAULT_TITLE
    const resolvedDescription = description ?? DEFAULT_DESCRIPTION
    const resolvedUrl = canonicalPath ? `${SITE_URL}${canonicalPath}` : SITE_URL
    const resolvedImage = image ?? DEFAULT_OG_IMAGE

    document.title = resolvedTitle
    upsertMeta('meta[name="description"]', 'name', 'description', resolvedDescription)

    // Open Graph is read by WhatsApp, Instagram and Facebook to draw the preview
    // card on a pasted link. It is not read by Google, and never affects a
    // ranking — but a seller's whole distribution is a pasted link.
    upsertMeta('meta[property="og:title"]', 'property', 'og:title', resolvedTitle)
    upsertMeta('meta[property="og:description"]', 'property', 'og:description', resolvedDescription)
    upsertMeta('meta[property="og:url"]', 'property', 'og:url', resolvedUrl)
    upsertMeta('meta[property="og:image"]', 'property', 'og:image', resolvedImage)
    upsertMeta('meta[name="twitter:title"]', 'name', 'twitter:title', resolvedTitle)
    upsertMeta('meta[name="twitter:description"]', 'name', 'twitter:description', resolvedDescription)
    upsertMeta('meta[name="twitter:image"]', 'name', 'twitter:image', resolvedImage)

    // "This is the real address of this page", so `?utm_...` and `?product=...`
    // variants are not counted as separate competing duplicates.
    let canonical = document.head.querySelector<HTMLLinkElement>('link[rel="canonical"]')
    if (!canonical) {
      canonical = document.createElement('link')
      canonical.rel = 'canonical'
      document.head.appendChild(canonical)
    }
    canonical.href = resolvedUrl

    let robots = document.head.querySelector<HTMLMetaElement>('meta[name="robots"]')
    if (noIndex) {
      if (!robots) {
        robots = document.createElement('meta')
        robots.setAttribute('name', 'robots')
        document.head.appendChild(robots)
      }
      robots.setAttribute('content', 'noindex, follow')
    } else {
      robots?.remove()
    }

    return () => {
      document.title = previousTitle
      document.head.querySelector('meta[name="robots"]')?.remove()
    }
  }, [title, description, canonicalPath, image, noIndex])
}
